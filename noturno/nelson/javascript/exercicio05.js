// Declaração de função tradicional utilizando a palavra-chave function
function converterParaFahrenheit(celsius) {
  // Aplica a fórmula matemática de conversão e retorna o resultado
  return (celsius * 9/5) + 32;
}

// Chamada da função passando 25 graus Celsius como argumento
console.log(converterParaFahrenheit(25));
